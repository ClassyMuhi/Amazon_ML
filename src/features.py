"""
Feature engineering module for Amazon Business Entity Resolution Challenge 2026.

Computes pairwise string, token, numerical, and structural similarity features
for candidate pairs generated by the blocking module using normalized attributes.
"""

from typing import Dict, List, Optional, Set, Tuple
import pandas as pd
import numpy as np

# RapidFuzz for high-performance C++ string matching with difflib fallback
try:
    from rapidfuzz import distance, fuzz
    _HAS_RAPIDFUZZ = True
except ImportError:
    import difflib
    _HAS_RAPIDFUZZ = False

from src.normalization import add_normalized_features


# ---------------------------------------------------------------------------
# String Distance & Similarity Helpers
# ---------------------------------------------------------------------------

def _levenshtein_ratio(s1: str, s2: str) -> float:
    """Calculates normalized Levenshtein similarity ratio in [0.0, 1.0]."""
    if not s1 or not s2:
        return 1.0 if not s1 and not s2 else 0.0
    if s1 == s2:
        return 1.0
    if _HAS_RAPIDFUZZ:
        return float(fuzz.ratio(s1, s2)) / 100.0
    return float(difflib.SequenceMatcher(None, s1, s2).ratio())


def _jaro_winkler_similarity(s1: str, s2: str) -> float:
    """Calculates Jaro-Winkler similarity score in [0.0, 1.0]."""
    if not s1 or not s2:
        return 1.0 if not s1 and not s2 else 0.0
    if s1 == s2:
        return 1.0
    if _HAS_RAPIDFUZZ:
        return float(distance.JaroWinkler.similarity(s1, s2))
    
    # Pure Python Jaro-Winkler implementation fallback
    len1, len2 = len(s1), len(s2)
    max_dist = (max(len1, len2) // 2) - 1
    if max_dist < 0:
        max_dist = 0

    s1_matches = [False] * len1
    s2_matches = [False] * len2

    matches = 0
    transpositions = 0

    for i in range(len1):
        start = max(0, i - max_dist)
        end = min(i + max_dist + 1, len2)
        for j in range(start, end):
            if s2_matches[j]:
                continue
            if s1[i] != s2[j]:
                continue
            s1_matches[i] = True
            s2_matches[j] = True
            matches += 1
            break

    if matches == 0:
        return 0.0

    k = 0
    for i in range(len1):
        if not s1_matches[i]:
            continue
        while not s2_matches[k]:
            k += 1
        if s1[i] != s2[k]:
            transpositions += 1
        k += 1

    jaro = (
        (matches / len1) + (matches / len2) + ((matches - transpositions / 2) / matches)
    ) / 3.0

    # Winkler prefix bonus (up to 4 prefix chars)
    prefix = 0
    for i in range(min(4, min(len1, len2))):
        if s1[i] == s2[i]:
            prefix += 1
        else:
            break

    return float(jaro + prefix * 0.1 * (1.0 - jaro))


def _token_sort_ratio(s1: str, s2: str) -> float:
    """Calculates token sort similarity ratio in [0.0, 1.0]."""
    if not s1 or not s2:
        return 1.0 if not s1 and not s2 else 0.0
    if s1 == s2:
        return 1.0
    if _HAS_RAPIDFUZZ:
        return float(fuzz.token_sort_ratio(s1, s2)) / 100.0

    sorted1 = " ".join(sorted(s1.split()))
    sorted2 = " ".join(sorted(s2.split()))
    return _levenshtein_ratio(sorted1, sorted2)


def _token_set_ratio(s1: str, s2: str) -> float:
    """Calculates token set similarity ratio in [0.0, 1.0]."""
    if not s1 or not s2:
        return 1.0 if not s1 and not s2 else 0.0
    if s1 == s2:
        return 1.0
    if _HAS_RAPIDFUZZ:
        return float(fuzz.token_set_ratio(s1, s2)) / 100.0

    set1 = set(s1.split())
    set2 = set(s2.split())
    intersection = set1 & set2
    if not intersection:
        return _levenshtein_ratio(s1, s2)

    sorted_intersection = " ".join(sorted(intersection))
    sorted1 = " ".join(sorted(set1))
    sorted2 = " ".join(sorted(set2))

    r1 = _levenshtein_ratio(sorted_intersection, sorted1)
    r2 = _levenshtein_ratio(sorted_intersection, sorted2)
    r3 = _levenshtein_ratio(sorted1, sorted2)
    return max(r1, r2, r3)


def _jaccard_similarity(tokens1: List[str], tokens2: List[str]) -> float:
    """Calculates Jaccard similarity between two token lists in [0.0, 1.0]."""
    if not tokens1 or not tokens2:
        return 0.0
    set1, set2 = set(tokens1), set(tokens2)
    intersection = len(set1 & set2)
    union = len(set1 | set2)
    return float(intersection / union) if union > 0 else 0.0


